// Turns the old Postgres database into SQL for D1, for the move off Docker.
//
// Postgres hands over its rows as JSON, and this writes statements that
// replace whatever D1 holds with them:
//
//   ssh nostromo "docker exec repair-cafe-telemetry-db psql -U telemetry -d telemetry -At -c \"
//     SELECT json_build_object(
//       'installs', (SELECT COALESCE(json_agg(i), '[]') FROM installs i),
//       'pings',    (SELECT COALESCE(json_agg(p ORDER BY p.id), '[]') FROM pings p))\"" \
//   | node scripts/export-postgres.mjs > export.sql
//   npx wrangler d1 execute repair-cafe-telemetry --remote --file export.sql
//
// Keep export.sql out of the repo: it holds café names and addresses.
//
// Times become milliseconds since 1970, and NUMERIC becomes a plain number.
// Ping ids are kept, so D1 carries on counting from where Postgres stopped.
// The directory is not copied: the first map request or the daily cron
// fetches it again.
import fs from 'node:fs';

const input = JSON.parse(fs.readFileSync(0, 'utf8'));

function literal(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
    return String(v);
  }
  if (typeof v === 'object') v = JSON.stringify(v);
  return `'${String(v).replaceAll("'", "''")}'`;
}

function ms(v) {
  if (v === null || v === undefined) return null;
  const t = new Date(v).getTime();
  if (!Number.isFinite(t)) throw new Error(`not a time: ${v}`);
  return t;
}

function num(v) {
  return v === null || v === undefined ? null : Number(v);
}

function insert(table, row) {
  const cols = Object.keys(row);
  return `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => literal(row[c])).join(', ')});`;
}

const out = [
  '-- Generated by scripts/export-postgres.mjs. Replaces everything in D1.',
  'DELETE FROM pings;',
  'DELETE FROM installs;',
];

for (const i of input.installs) {
  out.push(
    insert('installs', {
      id: i.id,
      token_hash: i.token_hash,
      created_at: ms(i.created_at),
      last_seen_at: ms(i.last_seen_at),
      app_version: i.app_version,
      level: i.level,
      country: i.country,
      cafe_slug: i.cafe_slug,
      cafe_name: i.cafe_name,
      cafe_url: i.cafe_url,
      cafe_lat: num(i.cafe_lat),
      cafe_lng: num(i.cafe_lng),
      is_blocked: Boolean(i.is_blocked),
      verified_at: ms(i.verified_at),
      verified_host: i.verified_host,
      verify_checked_at: ms(i.verify_checked_at),
      verify_error: i.verify_error,
      verified_repairs_recorded: num(i.verified_repairs_recorded),
      verified_repairs_fixed: num(i.verified_repairs_fixed),
      verified_repairs_not_fixed: num(i.verified_repairs_not_fixed),
      verified_sessions_held: num(i.verified_sessions_held),
      verified_volunteers: num(i.verified_volunteers),
      verified_co2_saved_kg: num(i.verified_co2_saved_kg),
    }),
  );
}

for (const p of input.pings) {
  out.push(
    insert('pings', {
      id: p.id,
      install_id: p.install_id,
      received_at: ms(p.received_at),
      sent_at: ms(p.sent_at),
      app_version: p.app_version,
      payload: p.payload,
      sessions_held: num(p.sessions_held),
      volunteers: num(p.volunteers),
      repairs_recorded: num(p.repairs_recorded),
      repairs_fixed: num(p.repairs_fixed),
      repairs_not_fixed: num(p.repairs_not_fixed),
      co2_saved_kg: num(p.co2_saved_kg),
    }),
  );
}

process.stdout.write(out.join('\n') + '\n');
console.error(`${input.installs.length} installs, ${input.pings.length} pings`);
