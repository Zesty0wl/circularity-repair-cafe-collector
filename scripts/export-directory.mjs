// Turns the Docker edition's cached copy of the repaircafe.org directory into
// SQL for D1, so the map keeps its pins on the day of the move even if
// repaircafe.org is down (it was, on 21 October 2026):
//
//   ssh nostromo 'docker exec repair-cafe-telemetry cat /data/repair-cafe-directory.json' \
//   | node scripts/export-directory.mjs > directory.sql
//   npx wrangler d1 execute repair-cafe-telemetry --remote --file directory.sql
//
// The daily cron replaces it with a fresh copy once repaircafe.org answers.
import fs from 'node:fs';

const snapshot = JSON.parse(fs.readFileSync(0, 'utf8'));
if (!snapshot?.bySlug || typeof snapshot.bySlug !== 'object') throw new Error('not a directory snapshot');

const literal = (v) =>
  v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;

const rows = Object.entries(snapshot.bySlug).filter(
  ([slug, e]) => slug && e?.name && Number.isFinite(e.lat) && Number.isFinite(e.lng),
);
const out = ['-- Generated by scripts/export-directory.mjs. Replaces the directory in D1.', 'DELETE FROM directory;'];
// Several rows per statement keeps the file short; D1 has no limit on literal
// values, only on bound ones.
for (let i = 0; i < rows.length; i += 50) {
  const values = rows
    .slice(i, i + 50)
    .map(([slug, e]) => `(${[slug, e.name, e.lat, e.lng, e.country, e.website].map(literal).join(', ')})`);
  out.push(`INSERT INTO directory (slug, name, lat, lng, country, website) VALUES\n${values.join(',\n')};`);
}
process.stdout.write(out.join('\n') + '\n');
console.error(`${rows.length} cafes, fetched ${snapshot.fetchedAt}`);
